import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root = new URL('../src/', import.meta.url);
const routes = [];
async function walk(relative) {
  for (const entry of await readdir(new URL(relative, root), { withFileTypes: true })) {
    const name = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) await walk(`${name}/`);
    else if (entry.name === 'route.ts') routes.push(name);
  }
}
await walk('app/api/research/');
const content = `// Generated by scripts/generate-route-registry.mjs.\nexport const researchRouteLoaders = {\n${routes.sort().map((file) => `  ${JSON.stringify(file.slice('app/api/'.length, -'/route.ts'.length))}: () => import(${JSON.stringify('./'+file)}),`).join('\n')}\n};\n`;
await writeFile(new URL('route-registry.ts', root), content);
console.log(`Registered ${routes.length} Research routes`);
